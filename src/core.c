void
run(void)
{
	XEvent ev;
	struct pollfd pfd = { .fd = ConnectionNumber(dpy), .events = POLLIN };
	int timeout;

	/* main event loop */
	XSync(dpy, False);
	while (running) {
		timeout = ui_bar_runupdateintervals();
		if (!XPending(dpy)) {
			poll(&pfd, 1, timeout);
			continue;
		}
		XNextEvent(dpy, &ev);
		if (ev.type < LASTEvent && handler[ev.type])
			handler[ev.type](&ev);
	}
}

